/**
 * Builds the declarative rulesets and generated content-script data.
 * No bundler, no runtime dependencies.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileFilterList } from './lib/compile.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const RULES_DIR = resolve(ROOT, 'rules');
const GENERATED_DIR = resolve(ROOT, 'src/content');
const SHARED_DIR = resolve(ROOT, 'src/shared');

const LISTS = [
  { id: 'ads', file: 'src/filters/ads.txt' },
  { id: 'trackers', file: 'src/filters/trackers.txt' },
  // The only ruleset allowed to block a top-level navigation, and only because
  // the whole point is to keep a person off a betting site.
  { id: 'gambling', file: 'src/filters/gambling.txt' },
];

function read(path) {
  return readFileSync(resolve(ROOT, path), 'utf8');
}

function write(path, contents) {
  const target = resolve(ROOT, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, contents);
}

function json(value) {
  return JSON.stringify(value, null, 2) + '\n';
}

const packageJson = JSON.parse(read('package.json'));
const manifestPath = resolve(ROOT, 'manifest.json');
if (!existsSync(manifestPath)) {
  throw new Error('manifest.json is missing');
}

mkdirSync(RULES_DIR, { recursive: true });
mkdirSync(GENERATED_DIR, { recursive: true });
mkdirSync(SHARED_DIR, { recursive: true });

const specific = new Map();
const exceptions = new Map();
const generic = new Set();
const ruleCounts = {};
const allSkipped = [];

function mergeSelectors(target, source) {
  for (const [domain, selectors] of Object.entries(source)) {
    if (!target.has(domain)) target.set(domain, new Set());
    for (const selector of selectors) target.get(domain).add(selector);
  }
}

for (const list of LISTS) {
  const result = compileFilterList(read(list.file), { source: list.file });
  if (result.rules.length === 0) {
    throw new Error(`${list.file} produced no DNR rules`);
  }
  let rules = result.rules;
  // Gambling ruleset is the deliberate exception: blocks whole sites including top-level navigation
  // by adding main_frame to resourceTypes. All other rulesets intentionally exclude main_frame.
  if (list.id === 'gambling') {
    rules = rules.map((rule) => ({
      ...rule,
      condition: {
        ...rule.condition,
        resourceTypes: ['main_frame', ...(rule.condition.resourceTypes || [])],
      },
    }));
  }
  write(`rules/${list.id}.json`, json(rules));
  ruleCounts[list.id] = rules.length;
  mergeSelectors(specific, result.cosmetics.specific);
  mergeSelectors(exceptions, result.cosmetics.exceptions);
  for (const selector of result.cosmetics.generic) generic.add(selector);
  allSkipped.push(...result.skipped);
  console.log(
    `${list.id}: ${rules.length} rules, ` +
      `${result.merged} duplicates merged, ${result.skipped.length} skipped`,
  );
}

function sortedObject(map) {
  return Object.fromEntries(
    [...map.entries()]
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([domain, selectors]) => [domain, [...selectors].sort()]),
  );
}

const cosmeticData = {
  version: 1,
  specific: sortedObject(specific),
  generic: [...generic].sort(),
  exceptions: sortedObject(exceptions),
};

write(
  'src/content/cosmetic-data.js',
  `/* GENERATED by scripts/build.mjs — do not edit. */\nglobalThis.FOCUS_COSMETIC = ${JSON.stringify(
    cosmeticData,
    null,
    2,
  )};\n`,
);

write(
  'src/shared/build-info.js',
  `/* GENERATED by scripts/build.mjs — do not edit. */\nglobalThis.FOCUS_BUILD = ${JSON.stringify(
    {
      version: packageJson.version,
      generated: new Date().toISOString().slice(0, 10),
      rules: ruleCounts,
      cosmetic: {
        domains: Object.keys(cosmeticData.specific).length,
        specificSelectors: Object.values(cosmeticData.specific).reduce(
          (total, selectors) => total + selectors.length,
          0,
        ),
        genericSelectors: cosmeticData.generic.length,
      },
    },
    null,
    2,
  )};\n`,
);

for (const skipped of allSkipped) {
  console.warn(`skip ${skipped.source}: ${skipped.reason} — ${skipped.line}`);
}

console.log(
  `cosmetic: ${Object.keys(cosmeticData.specific).length} domains, ` +
    `${cosmeticData.generic.length} generic selectors`,
);
